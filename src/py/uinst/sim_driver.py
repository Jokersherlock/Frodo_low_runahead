def gen_driver_rom_cases(hex_str, start_addr=0):
    group_len = 16
    num_groups = (len(hex_str) + group_len - 1) // group_len

    print("case (load_addr)")
    for i in range(num_groups):
        addr = start_addr + i
        addr_hex = f"{addr:03x}"
        data = hex_str[i*group_len:(i+1)*group_len].ljust(group_len, '0')
        # 字节反转（每2个字符为1字节，低位在前）
        data_bytes = [data[j:j+2] for j in range(0, len(data), 2)]
        data_reversed = ''.join(data_bytes[::-1])
        print(f"    12'h{addr_hex}: data_dout <= 64'h{data_reversed.upper()};")
    print("endcase\n")

    print("case (load_addr)")
    for i in range(num_groups):
        addr = start_addr + i
        addr_hex = f"{addr:03x}"
        load_addr_dout = f"{addr:04x}"
        print(f"    12'h{addr_hex}: load_addr_dout <= 14'h{load_addr_dout};")
    print("endcase")

def transform_hex(hex_str):
    # 1. 拆分为单字符
    chars = list(hex_str)
    # 2. 每个字符填充为4位十六进制
    padded = [f"{c:0>4}" for c in chars]  # 右侧补零填充
    # 3. 按反向索引顺序重组
    reordered = padded[::-1]  # 反转顺序
    reordered = [reordered[1],reordered[0],reordered[3],reordered[2]]
    # 4. 合并结果
    result = "".join(reordered)
    return result


